  /* ── Engine ──────────────────────────────────────── */
  var currentLang = 'tr';

  function applyLang(lang) {
    var d = dict[lang] || dict['tr'];
    var els = document.querySelectorAll('[data-i18n]');
    for (var i = 0; i < els.length; i++) {
      var key = els[i].getAttribute('data-i18n');
      if (d[key] !== undefined) els[i].textContent = d[key];
    }
    /* Update all lang selects to reflect current lang */
    var selects = document.querySelectorAll('.lang-select');
    for (var j = 0; j < selects.length; j++) {
      selects[j].value = lang;
    }
    document.documentElement.lang = lang;
    currentLang = lang;
  }

  function setLang(lang) {
    if (!dict[lang]) lang = 'tr';
    try { localStorage.setItem('lang', lang); } catch (e) {}
    applyLang(lang);
  }

  /* Init */
  var saved = 'tr';
  try { saved = localStorage.getItem('lang') || 'tr'; } catch (e) {}
  if (!dict[saved]) saved = 'tr';
  applyLang(saved);

  /* Select dropdowns */
  document.addEventListener('change', function (e) {
    if (e.target && e.target.classList.contains('lang-select')) {
      setLang(e.target.value);
    }
  });

  window.setLang = setLang;
  window.getLang = function () { return currentLang; };
